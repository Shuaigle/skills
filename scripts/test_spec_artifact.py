"""Exercise the documented CLI with offline issue bodies; never access GitHub."""

import hashlib
import json
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest


SCRIPT = Path(__file__).resolve().parents[1] / 'skills/to-spec/scripts/spec_artifact.py'
SPEC = b'<!-- generated by to-spec -->\n<!-- feature: inbox-search -->\n\n## Problem Statement\nFind a message.\n'
BEGIN = b'<!-- to-spec:begin -->\n'
END = b'<!-- to-spec:end -->\n'
BLOCK = 'to-spec-block-v1'
WHOLE = 'whole-artifact-v1'


class SpecArtifactTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.sequence = 0

    def file(self, name, value):
        path = self.root / name
        path.write_bytes(value)
        return path

    def run_cli(self, *args, success=True):
        result = subprocess.run([sys.executable, str(SCRIPT), *map(str, args)],
                                capture_output=True, text=True, timeout=5)
        self.assertEqual(result.returncode == 0, success, result.stderr)
        return json.loads(result.stdout) if success else result.stderr

    def compose(self, body, spec=SPEC, expected=None, success=True):
        self.sequence += 1
        prefix = str(self.sequence)
        original = self.file(prefix + '-expected.md', body if expected is None else expected)
        current = self.file(prefix + '-current.md', body)
        draft = self.file(prefix + '-spec.md', spec)
        output = self.root / (prefix + '-output.md')
        result = self.run_cli('compose-issue', '--expected', original, '--current', current,
                              '--spec', draft, '--feature', 'inbox-search', '--output', output,
                              success=success)
        self.assertEqual(current.read_bytes(), body)
        self.assertEqual(draft.read_bytes(), spec)
        if not success:
            self.assertFalse(output.exists())
            return result
        return output.read_bytes(), result

    def inspect(self, body, source_slice=None, feature=None, success=True):
        path = self.file('readback.md', body)
        args = ['source', '--input', path]
        if source_slice is not None:
            args += ['--slice', source_slice]
        if feature is not None:
            args += ['--feature', feature]
        return self.run_cli(*args, success=success)

    def test_append_and_rerun_preserve_original_text_and_checkboxes(self):
        human = '# Original task\r\n人工備註\r\n- [x] done\r\n- [ ] pending\r\n<!-- human note -->'.encode()
        body, metadata = self.compose(human)
        self.assertEqual(body, human + b'\n\n' + BEGIN + SPEC + END)
        self.assertEqual(metadata, self.inspect(body, BLOCK, 'inbox-search'))
        again, _ = self.compose(body)
        self.assertEqual(again, body)
        self.assertEqual(again.count(BEGIN), 1)

    def test_update_only_payload_with_human_prefix_and_suffix(self):
        prefix = b'# Human request\n- [x] original acceptance\n\n'
        suffix = b'\n## Later notes\n- [ ] manually tracked\n<!-- human comment -->\n'
        body = prefix + BEGIN + SPEC + END + suffix
        new_spec = SPEC.replace(b'Find a message.', b'Find archived messages too.')
        result, metadata = self.compose(body, new_spec)
        self.assertEqual(result, prefix + BEGIN + new_spec + END + suffix)
        self.assertEqual(metadata['sha256'], hashlib.sha256(new_spec).hexdigest())
        self.assertNotEqual(metadata['sha256'], self.inspect(body)['sha256'])

    def test_outside_prose_and_checkbox_change_do_not_churn_managed_hash(self):
        before = b'- [ ] task\n' + BEGIN + SPEC + END + b'Human note.\n'
        after = before.replace(b'[ ]', b'[x]').replace(b'Human note.', b'New human note.')
        self.assertEqual(self.inspect(before, BLOCK), self.inspect(after, BLOCK))
        self.assertNotEqual(self.inspect(before, WHOLE), self.inspect(after, WHOLE))

    def test_generated_ticket_host_retains_ticket_body_and_acceptance(self):
        ticket = b'<!-- generated by to-tickets -->\n<!-- feature: inbox-search -->\n<!-- ticket: 01-search -->\n- [x] Tested\n'
        body, metadata = self.compose(ticket)
        self.assertTrue(body.startswith(ticket + b'\n\n' + BEGIN))
        self.assertEqual(metadata['source_slice'], BLOCK)
        self.assertEqual(metadata['feature'], 'inbox-search')

    def test_existing_standalone_spec_keeps_whole_body_format(self):
        updated = SPEC.replace(b'message.', b'saved message.')
        body, metadata = self.compose(SPEC, updated)
        self.assertEqual(body, updated)
        self.assertNotIn(BEGIN, body)
        self.assertEqual(metadata['source_slice'], WHOLE)
        self.assertEqual(metadata['sha256'], hashlib.sha256(updated).hexdigest())

    def test_legacy_recorded_whole_hash_does_not_silently_switch(self):
        managed, _ = self.compose(b'Human task')
        metadata = self.inspect(managed, WHOLE)
        self.assertEqual(metadata['sha256'], hashlib.sha256(managed).hexdigest())
        self.assertNotEqual(metadata['sha256'], self.inspect(managed, BLOCK)['sha256'])

    def test_local_whole_file_including_marker_examples_stays_byte_exact(self):
        local = b'User supplied spec\r\nExample: <!-- to-spec:begin -->\r\n'
        self.assertEqual(self.inspect(local, WHOLE)['sha256'], hashlib.sha256(local).hexdigest())

    def test_utf8_crlf_and_final_newline_are_not_normalized(self):
        spec = SPEC.replace(b'Find a message.', '尋找訊息。'.encode()).replace(b'\n', b'\r\n')
        body = BEGIN.replace(b'\n', b'\r\n') + spec + END.replace(b'\n', b'\r\n')
        self.assertEqual(self.inspect(body, BLOCK)['sha256'], hashlib.sha256(spec).hexdigest())
        changed = body.replace(b'\r\n', b'\n')
        self.assertNotEqual(self.inspect(body, BLOCK)['sha256'], self.inspect(changed, BLOCK)['sha256'])
        self.assertNotEqual(self.inspect(SPEC, WHOLE)['sha256'], self.inspect(SPEC[:-1], WHOLE)['sha256'])

    def test_stale_read_stops_before_writing_even_for_unrelated_change(self):
        self.assertIn('changed since', self.compose(b'New human note', expected=b'Old human note', success=False))
        managed = BEGIN + SPEC + END
        self.compose(managed + b'New note', expected=managed, success=False)

    def test_malformed_and_multiple_blocks_stop_composition_and_selection(self):
        cases = [BEGIN + SPEC, END, END + BEGIN + SPEC, BEGIN + SPEC + END + BEGIN + SPEC + END,
                 BEGIN + BEGIN + SPEC + END + END, b' ' + BEGIN + SPEC + END,
                 BEGIN + b'Unmarked spec\n' + END, b'<!-- to-spec:begin --> trailing\n',
                 b'<!-- to-spec:unknown -->\n']
        for body in cases:
            with self.subTest(body=body):
                self.compose(body, success=False)
                self.inspect(body, success=False)
                self.inspect(body, BLOCK, success=False)

    def test_wrong_feature_stops_in_both_formats(self):
        other = SPEC.replace(b'inbox-search', b'other-feature')
        for body in (other, BEGIN + other + END):
            with self.subTest(body=body):
                self.compose(body, success=False)
                self.inspect(body, feature='inbox-search', success=False)

    def test_missing_recorded_block_and_unknown_slice_stop(self):
        self.inspect(SPEC, BLOCK, success=False)
        self.inspect(SPEC, 'unknown-v1', success=False)

    def test_invalid_payload_never_writes_a_draft(self):
        for draft in (b'Unmarked\n', SPEC[:-1], SPEC.replace(b'inbox-search', b'other'),
                      BEGIN + SPEC + END, SPEC + b'<!-- to-spec:broken -->\n', SPEC + b'\xff\n'):
            with self.subTest(draft=draft):
                self.compose(b'Human task', draft, success=False)

    def test_ticket_target_rejects_any_managed_host_before_full_replacement(self):
        ticket = b'<!-- generated by to-tickets -->\n<!-- feature: inbox-search -->\n<!-- ticket: 01-search -->\n- [x] Tested\n'
        # The canonical source may be another issue; every embedded spec is protected.
        other_spec = SPEC.replace(b'inbox-search', b'other-feature')
        for spec in (SPEC, other_spec):
            body = ticket + BEGIN + spec + END
            path = self.file('target.md', body)
            self.run_cli('ticket-target', '--input', path, '--feature', 'inbox-search',
                         '--ticket', '01-search', success=False)
            self.assertEqual(path.read_bytes(), body)
        path = self.file('target.md', ticket)
        self.assertEqual(self.run_cli('ticket-target', '--input', path, '--feature', 'inbox-search',
                                     '--ticket', '01-search'), {'safe_to_replace': True})

    def test_ticket_target_rejects_unmarked_mismatched_and_malformed_bodies(self):
        ticket = b'<!-- generated by to-tickets -->\n<!-- feature: inbox-search -->\n<!-- ticket: 01-search -->\n'
        for body in (b'Human task', ticket.replace(b'01-search', b'02-search'),
                     ticket.replace(b'inbox-search', b'other'), ticket + BEGIN + SPEC,
                     ticket + BEGIN + SPEC + END + BEGIN + SPEC + END):
            path = self.file('target.md', body)
            self.run_cli('ticket-target', '--input', path, '--feature', 'inbox-search',
                         '--ticket', '01-search', success=False)
            self.assertEqual(path.read_bytes(), body)

    def test_invalid_utf8_source_stops(self):
        self.inspect(b'\xff', WHOLE, success=False)
        self.compose(b'\xff', success=False)

    def test_existing_output_is_not_overwritten(self):
        current = self.file('current.md', b'Human task')
        spec = self.file('spec.md', SPEC)
        output = self.file('output.md', b'Keep this draft')
        self.run_cli('compose-issue', '--current', current, '--expected', current,
                     '--spec', spec, '--feature', 'inbox-search', '--output', output, success=False)
        self.assertEqual(output.read_bytes(), b'Keep this draft')

    def test_empty_issue_can_host_one_block(self):
        body, metadata = self.compose(b'')
        self.assertEqual(body, BEGIN + SPEC + END)
        self.assertEqual(metadata['sha256'], hashlib.sha256(SPEC).hexdigest())


if __name__ == '__main__':
    unittest.main()
