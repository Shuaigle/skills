#!/usr/bin/env python3
"""Compose issue-body drafts and hash spec sources without network access."""

import argparse
import hashlib
import json
from pathlib import Path
import re


GENERATED = b"<!-- generated by to-spec -->"
BEGIN = b"<!-- to-spec:begin -->"
END = b"<!-- to-spec:end -->"
WHOLE = "whole-artifact-v1"
BLOCK = "to-spec-block-v1"


def feature_of(spec):
    lines = spec.splitlines()
    if not lines or lines[0] != GENERATED or len(lines) < 2:
        return None
    match = re.fullmatch(rb"<!-- feature: ([a-z0-9]+(?:-[a-z0-9]+)*) -->", lines[1])
    return match[1].decode("ascii") if match else None


def block_span(body):
    """Return payload offsets; reject ambiguous or malformed reserved markers."""
    markers = []
    offset = 0
    for line in body.splitlines(keepends=True):
        text = line.rstrip(b"\r\n")
        if b"<!-- to-spec:" in line:
            if text not in (BEGIN, END):
                raise ValueError("malformed to-spec boundary")
            markers.append((text, offset, offset + len(line)))
        offset += len(line)
    if not markers:
        return None
    if len(markers) != 2 or markers[0][0] != BEGIN or markers[1][0] != END:
        raise ValueError("expected exactly one ordered to-spec block")
    start, stop = markers[0][2], markers[1][1]
    if not feature_of(body[start:stop]):
        raise ValueError("managed block needs generated and feature markers")
    return start, stop


def source(body, source_slice=None, feature=None):
    body.decode("utf-8")
    selected = source_slice
    # A recorded legacy whole-body hash must not acquire block semantics.
    if selected is None:
        selected = BLOCK if block_span(body) else WHOLE
    if selected == BLOCK:
        span = block_span(body)
        if span is None:
            raise ValueError("recorded managed block is missing")
        # An issue editor may normalize the full body, including our unchanged block.
        payload = body[span[0]:span[1]].replace(b"\r\n", b"\n")
    elif selected == WHOLE:
        payload = body
    else:
        raise ValueError("unknown source slice")
    actual_feature = feature_of(payload)
    if feature is not None and actual_feature != feature:
        raise ValueError("source feature does not match")
    return {
        "source_slice": selected,
        "feature": actual_feature,
        "sha256": hashlib.sha256(payload).hexdigest(),
    }


def compose_issue(current, expected, spec, feature):
    if current != expected:
        raise ValueError("issue body changed since it was read")
    current.decode("utf-8")
    spec.decode("utf-8")
    if feature_of(spec) != feature or not spec.endswith(b"\n"):
        raise ValueError("draft needs matching generated/feature markers and a final newline")
    if block_span(spec) is not None:
        raise ValueError("draft must be the spec payload, not a wrapped block")
    span = block_span(current)
    if span is not None:
        if feature_of(current[span[0]:span[1]]) != feature:
            raise ValueError("existing block belongs to another feature")
        return current[:span[0]] + spec + current[span[1]:]
    if current.splitlines()[:1] == [GENERATED]:
        if feature_of(current) != feature:
            raise ValueError("standalone spec belongs to another or unknown feature")
        return spec
    separator = b"\n\n" if current else b""
    return current + separator + BEGIN + b"\n" + spec + END + b"\n"



def ticket_target(body, feature, ticket):
    body.decode("utf-8")
    if block_span(body) is not None:
        raise ValueError("managed spec host cannot be replaced as a ticket")
    expected = [b"<!-- generated by to-tickets -->",
                f"<!-- feature: {feature} -->".encode("utf-8"),
                f"<!-- ticket: {ticket} -->".encode("utf-8")]
    if body.splitlines()[:3] != expected:
        raise ValueError("existing ticket identity does not match")
    return {"safe_to_replace": True}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    inspect = commands.add_parser("source", help="report source slice, feature and SHA-256")
    inspect.add_argument("--input", type=Path, required=True)
    inspect.add_argument("--slice", choices=(WHOLE, BLOCK))
    inspect.add_argument("--feature")
    target = commands.add_parser("ticket-target", help="reject protected hosts or conflicting ticket identity")
    target.add_argument("--input", type=Path, required=True)
    target.add_argument("--feature", required=True)
    target.add_argument("--ticket", required=True)
    compose = commands.add_parser("compose-issue", help="prepare a body-only draft; does not publish")
    for name in ("current", "expected", "spec", "output"):
        compose.add_argument(f"--{name}", type=Path, required=True)
    compose.add_argument("--feature", required=True)
    args = parser.parse_args()
    try:
        if args.command == "source":
            result = source(args.input.read_bytes(), args.slice, args.feature)
        elif args.command == "ticket-target":
            result = ticket_target(args.input.read_bytes(), args.feature, args.ticket)
        else:
            if args.output.exists():
                raise ValueError("output must be a new temporary file")
            body = compose_issue(args.current.read_bytes(), args.expected.read_bytes(),
                                 args.spec.read_bytes(), args.feature)
            result = source(body, feature=args.feature)
            with args.output.open("xb") as output:
                output.write(body)
        print(json.dumps(result, sort_keys=True))
    except (OSError, ValueError) as error:
        parser.exit(1, f"error: {error}\n")


if __name__ == "__main__":
    main()
